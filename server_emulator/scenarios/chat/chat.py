"""Болталка (TASK-080): узкий набор фраз, ответы своими словами, несколько вариантов.

Образцы (захват 2026-11-02) — обычные речевые ответы; формулировки свои, ответы Алисы
не копируются. «Кто тебя создал» — честно: эмулятор, исследовательский проект.
«Спой» — честный отказ (синтез не поёт). «Повтори за мной» повторяет фразу как
колонка в образце. Интенты разбираются по ключевым словам текста: сопутствующие
слова («пожалуйста») не мешают.
"""
import random

from server_emulator.sdk import say

HOW = [
    "Отлично! Всё работает как часы.",
    "Хорошо! Слушаю вас внимательно.",
    "Прекрасно! Рад служить.",
]
WHO = [
    "Я эмулятор умной колонки — исследовательский проект. Меня собрали разработчики этого проекта.",
    "Я часть эмулятора сервера Алисы: исследовательский проект, где колонку обслуживает свой сервер.",
]
SKILLS = ("Я умею говорить время и дату, ставить таймеры и будильники, показывать погоду, "
          "управлять громкостью, поболтать и сыграть с вами в простые игры.")
TONGUE_TWISTERS = [
    "Шла Саша по шоссе и сосала сушку.",
    "Карл у Клары украл кораллы.",
    "На дворе трава, на траве дрова.",
    "Четыре чёрненьких чумазеньких чертёнка чертили чёрными чернилами чертёж.",
    "Наш Полкан попал в капкан.",
]
POEMS = [
    "Уронили мишку на пол, оторвали мишке лапу. Всё равно его не брошу, потому что он хороший.",
    "Наша Таня громко плачет: уронила в речку мячик. Тише, Танечка, не плачь: не утонет в речке мяч.",
    "Идёт бычок, качается, вздыхает на ходу: ох, доска кончается, сейчас я упаду.",
]
TOASTS = [
    "Выпьем за то, чтобы каждый день приносил больше поводов для радости, чем для забот!",
    "За здоровье хозяев и гостеприимство этого дома!",
    "Пусть в доме всегда будет тепло, а в сердце — спокойно. За вас!",
]
CHANTS = [
    "Раз, два, три, четыре, пять — выходи гулять!",
    "Мы команда просто класс, всё получится у нас!",
    "Выше ноги, шире шаг — так держать, и никак!",
]
SING = "Петь я не умею — синтез речи не берёт такие ноты. Зато могу включить музыку: скажите «включи музыку»."


def _pick_variants(*phrases):
    return random.choice(phrases)


def handle(ctx):
    text = ctx.text.lower().strip(" .!?,")

    if "повтори за мной" in text:
        start = text.index("повтори за мной") + len("повтори за мной")
        rest = ctx.text[start:].strip(" .!?")
        if not rest:
            return say("Что повторить? Скажите: «повтори за мной» и фразу.")
        return say(rest + ".")

    if "поёшь" in text or text.startswith("спой") or " спой" in text:
        return say(SING)
    if "скороговорк" in text:
        return say(_pick_variants(*TONGUE_TWISTERS))
    if "стих" in text:
        return say(_pick_variants(*POEMS))
    if "тост" in text:
        return say(_pick_variants(*TOASTS))
    if "кричалк" in text:
        return say(_pick_variants(*CHANTS))
    if "умеешь" in text or "можешь" in text:
        return say(SKILLS)
    if "создал" in text or "сделал" in text or "придумал" in text or text.startswith("кто ты"):
        return say(_pick_variants(*WHO))
    return say(_pick_variants(*HOW))
